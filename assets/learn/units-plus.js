/* New Learn-path units (U16+). Their questions live in assets/learn/extra-questions.js (Turkish) and its hash-checked
   language packs; their path metadata (section, name, description, stage titles in five languages) is
   window.DEEN_UNITS_PLUS_META, generated by scripts/learn-extra/build.py.
   All of this content is model-authored and has not been reviewed by a religious expert (the question flags stay false).
   The owner chose to publish it to every player (LIVE = true). Setting LIVE back to false hides the units again, except
   on a device where the admin panel's "Yeni üniteler" switch is on (localStorage deen_admin_units_plus = '1').
   The core keeps its unit list in the globals U, DESC, COLORS, DEEN512_UNIT_STYLES, STAGES and POOLS; the units are
   appended to them in order (U16 right after U15), then the path is drawn again. */
(()=>{
 'use strict';
 if(window.DEEN_UNITS_PLUS)return;
 const LIVE=true;
 const KEY='deen_admin_units_plus';
 const meta=window.DEEN_UNITS_PLUS_META||{units:[],sections:{}};
 const lang=()=>{try{return window.DEEN_APP_LOCALE?.get?.()||'tr'}catch(_){return 'tr'}};
 const previewOn=()=>{try{return localStorage.getItem(KEY)==='1'}catch(_){return false}};
 const enabled=()=>LIVE||previewOn();
 const pick=(obj,l)=>obj?.[l]||obj?.tr||'';
 const SECTION_WORD={tr:n=>'KISIM '+n,en:n=>'SECTION '+n,de:n=>'ABSCHNITT '+n,fr:n=>'SECTION '+n,
  ar:n=>'القسم '+({4:'الرابع',5:'الخامس',6:'السادس',7:'السابع'}[n]||n)};
 const NEXT={tr:['SONRAKİ ÜNİTE','SON ÜNİTE'],en:['NEXT UNIT','LAST UNIT'],de:['NÄCHSTE EINHEIT','LETZTE EINHEIT'],
  fr:['UNITÉ SUIVANTE','DERNIÈRE UNITÉ'],ar:['الوحدة التالية','الوحدة الأخيرة']};
 const STYLES=[
  {a:'#e6b955',b:'#ffe08f',bg:'linear-gradient(116deg,rgba(54,44,20,.98),rgba(9,28,35,.99))'},
  {a:'#d98f5c',b:'#ffc39a',bg:'linear-gradient(116deg,rgba(58,36,24,.98),rgba(10,29,36,.99))'},
  {a:'#5fb7e0',b:'#a8dcf5',bg:'linear-gradient(116deg,rgba(16,44,64,.98),rgba(7,25,38,.99))'},
  {a:'#3ecf9e',b:'#8ff0cb',bg:'linear-gradient(116deg,rgba(12,52,44,.98),rgba(6,27,35,.99))'},
  {a:'#8aa6f0',b:'#c3d2ff',bg:'linear-gradient(116deg,rgba(28,36,74,.98),rgba(8,25,39,.99))'}
 ];
 const COLOR=['#d8b25e','#d29b74','#6db5d4','#5dc7a2','#94a8e0'];
 let added=[];

 // Units whose questions exist in the active language (Turkish always; others once the unit's pack is complete).
 function available(){
  const l=lang();
  const out=[];
  for(const m of meta.units||[]){
   if(l!=='tr'&&!(m.langs||[]).includes(l))break;
   out.push(m);
  }
  return out;
 }

 function install(){
  if(added.length||!enabled())return false;
  if(typeof U==='undefined'||typeof STAGES==='undefined'||U.length!==15)return false;
  const l=lang(),list=available();
  list.forEach((m,i)=>{
   U.push(pick(m.name,l));
   DESC.push(pick(m.desc,l));
   try{COLORS.push(COLOR[i%COLOR.length])}catch(_){}
   try{DEEN512_UNIT_STYLES.push(STYLES[i%STYLES.length])}catch(_){}
   for(const s of m.stages){
    const no=String(Number(s.id.slice(-2)));
    STAGES.push({...s,title:m.titles?.[l]?.[no]||m.titles?.tr?.[no]||s.title});
    try{POOLS.set(s.id,[])}catch(_){}
   }
   added.push(m.unit);
  });
  return added.length>0;
 }

 function sectionOf(i){const m=(meta.units||[])[i-15];return m?m.section:null}
 // Divider drawn before the unit at index i (0-based) of the path; i >= 15 only.
 function divider(i){
  const sec=sectionOf(i);if(!sec)return '';
  const l=lang(),prev=sectionOf(i-1);
  if(sec!==prev){
   const name=pick(meta.sections?.[String(sec)],l);
   return '<div class="restore-section-divider units-plus-section" data-section="'+sec+'">'+SECTION_WORD[l in SECTION_WORD?l:'tr'](sec)+' · '+String(name).toLocaleUpperCase(l==='tr'?'tr':l)+'</div>';
  }
  const last=sectionOf(i+1)!==sec;
  return '<div class="restore-section-divider">'+(NEXT[l]||NEXT.tr)[last?1:0]+'</div>';
 }
 function world(i){return sectionOf(i)||Math.floor(i/5)+1}

 function redraw(){
  try{window.DEEN_FIVE_STAGE?.sync?.()}catch(_){}
  try{if(typeof renderPaths==='function'&&document.getElementById('v5Paths'))renderPaths()}catch(e){console.warn('[DEEN units+]',e)}
  try{if(typeof updateUI==='function')updateUI()}catch(_){}
 }

 window.DEEN_UNITS_PLUS=Object.freeze({
  live:LIVE,enabled,units:()=>added.slice(),divider,world,sectionOf,
  isPlus:u=>added.includes(u)
 });
 window.DEEN_UNIT_COUNT=()=>{try{return U.length}catch(_){return 15}};

 if(install()){
  // Another language's questions arrive with its pack; the path is drawn now and again once that pack is in.
  const l=lang();
  if(l!=='tr'){try{window.DEEN_EXTRA_I18N_LOAD?.(l)?.then?.(()=>redraw())}catch(_){}}
  redraw();
 }
})();
