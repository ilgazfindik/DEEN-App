// Builds the 2026-10 Turkish-leak translations for the Arabic and French UI layers from one source file.
// AR: an idempotent <script> block at the end of release segment 66 (registers only keys Arabic cannot translate yet).
// FR: a staging pack that fr/runtime-ui.js merges after its reviewed packs (existing keys always win).
// DE: a staging pack that de/runtime-ui.js uses only when the German packs have no translation.
// Run `node scripts/build-release-manifest.mjs` afterwards to refresh the segment hashes.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const source=JSON.parse(readFileSync(root+'scripts/i18n/leak-audit-2026-10.source.json','utf8'));
// Static groups share one key space; a null slot means that language already covers the key.
const STATIC_GROUPS=['static','static_wave2','source_notes','source_notes_2'];
const pick=(groups,i)=>Object.fromEntries(groups.flatMap(g=>Object.entries(source[g]||{})).filter(([,v])=>typeof v[i]==='string'&&v[i].trim()).map(([k,v])=>[k,v[i]]));

const frTranslations={...pick(STATIC_GROUPS,1),...pick(['dynamic'],1)};
const frPack={schema_version:1,locale:'fr',scope:'ui_leak_audit_2026_10',status:'translation_draft_requires_native_review',
 source_language:'tr',release_ready:false,native_reviewer_approved:false,verified_by_religious_expert:false,
 translation_count:Object.keys(frTranslations).length,
 source_reference:'scripts/i18n/leak-audit-2026-10.source.json',translations:frTranslations};
writeFileSync(root+'assets/i18n/fr/ui.leak-audit-2026-10.staging.json',JSON.stringify(frPack,null,2)+'\n');

// DE: one map of exact keys and {n}/{unit}/{topic} templates, read by assets/i18n/de/runtime-ui.js.
const deTranslations=Object.fromEntries(Object.entries(source.de||{}).filter(([,v])=>typeof v==='string'&&v.trim()));
const dePack={...frPack,locale:'de',translation_count:Object.keys(deTranslations).length,translations:deTranslations};
writeFileSync(root+'assets/i18n/de/ui.leak-audit-2026-10.staging.json',JSON.stringify(dePack,null,2)+'\n');

const START='<!-- DEEN_LEAK_AUDIT_AR_START -->',END='<!-- DEEN_LEAK_AUDIT_AR_END -->';
const safe=s=>JSON.stringify(s).replace(/<\//g,'<\\/');
const block=`${START}
<script id="deen-leak-audit-2026-10-ar">
/* 2026-10 Turkish-leak audit (generated by scripts/build-leak-audit-i18n.mjs). Reviewed Arabic copy wins. */
(()=>{
 const S=${safe(pick(STATIC_GROUPS,0))},P=${safe(pick(['dynamic'],0))};
 const A=window.DEEN_ARABIC_UI;if(!A||typeof A.register!=='function')return;
 const turkish=/[çğıöşüÇĞİÖŞÜ]/,add={};
 for(const k in S){const v=A.translate(k);if(v===k||turkish.test(v))add[k]=S[k]}
 const esc=s=>s.replace(/[\\^$.*+?()[\\]{}|]/g,'\\\\$&');
 const patterns=Object.entries(P).map(([k,out])=>({out,re:new RegExp('^'+k.split(/(\\{n\\}|\\{unit\\})/).map(p=>p==='{n}'?'(\\\\d+)':p==='{unit}'?'(.+?)':esc(p)).join('')+'$','u')}));
 // Unit titles can arrive in Turkish upper case ("İSLAM NEDİR?"): retry with the title-case dictionary key.
 const part=p=>{
  const v=A.translate(p);if(v!==p&&!turkish.test(v))return v;
  const core=p.trim();if(core!==core.toLocaleUpperCase('tr'))return v;
  const title=core.toLocaleLowerCase('tr').replace(/(^|[\\s(])(\\p{L})/gu,(_,a,b)=>a+b.toLocaleUpperCase('tr'));
  const w=A.translate(title);return w!==title&&!turkish.test(w)?p.replace(core,w):v;
 };
 // part() calls A.translate(), which runs this extension again; nested passes only see dictionary output.
 let nested=false;
 A.register(text=>{
  if(nested)return text;
  nested=true;
  try{
   const lead=text.match(/^\\s*/)[0],tail=text.match(/\\s*$/)[0],core=text.trim();
   for(const p of patterns){const m=p.re.exec(core);if(m){let i=1;return lead+p.out.replace(/\\{(?:n|unit)\\}/g,()=>{const v=m[i++];return /\\d/.test(v)?v:A.translate(v)})+tail}}
   // Composite labels ("Sıradaki: Ayırt Et · …") can arrive half-translated; finish the Turkish parts one by one.
   const parts=text.split(/(\\s*[·:]\\s*)/);
   if(parts.length>1&&turkish.test(text))return parts.map((p,i)=>i%2||!turkish.test(p)?p:part(p)).join('');
   if(turkish.test(text))return part(text);
   return text;
  }finally{nested=false}
 },add);
})();
</script>
${END}`;
const segPath=root+'release/v9.9.3-direct/segment-66.txt';
let seg=readFileSync(segPath,'utf8');
const a=seg.indexOf(START),b=seg.indexOf(END);
seg=a>=0&&b>a?seg.slice(0,a)+block+seg.slice(b+END.length):seg.replace(/\s*$/,'')+'\n'+block+'\n';
writeFileSync(segPath,seg);
console.log('DE pack:',dePack.translation_count,'· FR pack:',frPack.translation_count,'· AR static:',Object.keys(pick(STATIC_GROUPS,0)).length,'· AR dynamic:',Object.keys(pick(['dynamic'],0)).length);
